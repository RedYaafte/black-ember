NVIM_PALETTE_PATH = ROOT / "nvim" / "lua" / "black-ember" / "palette.lua"
VSCODE_THEME_PATH = ROOT / "vscode" / "themes" / "black-ember-color-theme.json"


def load_palette() -> dict:
    with PALETTE_PATH.open("rb") as palette_file:
        return tomllib.load(palette_file)


def render_lua(palette: dict) -> str:
    ui = palette["ui"]
    syntax = palette["syntax"]
    diagnostic = palette["diagnostic"]
    vcs = palette["vcs"]
    normal = palette["terminal"]["normal"]
    bright = palette["terminal"]["bright"]

    def table(name: str, values: dict, rename: dict[str, str] | None = None) -> list[str]:
        rename = rename or {}
        lines = [f"  {name} = {{"]
        for key, value in values.items():
            lines.append(f'    {rename.get(key, key)} = "{value}",')
        lines.append("  },")
        return lines

    def color_list(values: dict) -> str:
        return ", ".join(f'"{color}"' for color in values.values())

    lines = [
        "-- Generated by scripts/generate_themes.py from palette/black-ember.toml.",
        "-- Do not edit this file directly.",
        "return {",
    ]
    lines.extend(table("ui", ui))
    lines.extend(table("syntax", syntax, {"function": "function_"}))
    lines.extend(table("diagnostic", diagnostic))
    lines.extend(table("vcs", vcs))
    lines.extend(
        [
            "  terminal = {",
            f"    normal = {{ {color_list(normal)} }},",
            f"    bright = {{ {color_list(bright)} }},",
            "  },",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


