def expected_outputs(palette: dict) -> dict[Path, str]:
    return {
        NVIM_PALETTE_PATH: render_lua(palette),
        VSCODE_THEME_PATH: render_vscode_theme(palette),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    outputs = expected_outputs(load_palette())
    stale_files = []

    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale_files.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    if stale_files:
        for path in stale_files:
            print(f"Generated file is stale: {path}", file=sys.stderr)
        print("Run: python3 scripts/generate_themes.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
